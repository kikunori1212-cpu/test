from __future__ import annotations


XOR_FLAG = bytes(
    [
        0xEB, 0xFC, 0xEE, 0xBC, 0xEA, 0xF3, 0xE4, 0xB8, 0xB8,
        0xE3, 0xD7, 0xE5, 0xB8, 0xE5, 0xD7, 0xE6, 0xB8, 0xD7,
        0xE0, 0xBC, 0xE6, 0xEC, 0xFB, 0xD7, 0xE2, 0xFD, 0xFB,
        0xFC, 0xD7, 0xF0, 0xB8, 0xFA, 0xA9, 0xF5,
    ]
)
XOR_KEY = 0x88


def main() -> None:
    flag = bytes(value ^ XOR_KEY for value in XOR_FLAG)
    print(flag.decode("ascii"))


if __name__ == "__main__":
    main()
